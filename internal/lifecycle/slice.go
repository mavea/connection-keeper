package lifecycle

// registerSlice быстро расширяет слайс до индекса id включительно.
// Параметры:
//   - slice: указатель на слайс, который нужно увеличить при необходимости.
//   - id: целевой индекс, под который должен быть доступен слот.
// Возвращаемые значения: отсутствуют.
//
// Важно: helper рассчитан на внутреннее использование и оптимизирован под скорость,
// а не под защиту от некорректного внешнего вызова.
func registerSlice[T any](slice *[]T, id int) {
	if id < 0 {
		return
	}

	if id < len(*slice) {
		return
	}

	*slice = append(*slice, make([]T, id-len(*slice)+1)...)
}
