package domain

import (
	rootDomain "connection-keeper/domain"
	"context"
)

// Generation описывает типизированный доступ к поколению соединения.
type Generation[C any] interface {
	// Conn возвращает объект поколения и функцию снятия удержания этого использования.
	//
	// Важно: вызов Conn может использоваться остаточными процессами, даже если поколение
	// уже выведено из активной эксплуатации на уровне lifecycle.
	//
	// Параметры: отсутствуют.
	// Возвращаемые значения:
	//   - *C: типизированный объект поколения.
	//   - CancelFunc: функция снятия удержания, полученного этим вызовом Conn.
	Conn() (*C, rootDomain.CancelFunc)
	GenerationAny
}

// GenerationAny описывает нетипизированный контракт поколения.
type GenerationAny interface {
	// Any возвращает объект поколения в виде any и функцию снятия удержания.
	//
	// Параметры: отсутствуют.
	// Возвращаемые значения:
	//   - any: объект поколения в нетипизированном виде.
	//   - CancelFunc: функция снятия удержания, полученного этим вызовом.
	Any() (any, rootDomain.CancelFunc)

	// Version возвращает номер поколения.
	//
	// Параметры: отсутствуют.
	// Возвращаемое значение:
	//   - uint: версия поколения в последовательности обновлений.
	Version() uint
	// Refs возвращает текущее количество удержаний поколения.
	//
	// Значение включает базовое удержание поколения и удержания, выданные через Conn/Any.
	//
	// Параметры: отсутствуют.
	// Возвращаемое значение:
	//   - int64: текущее число активных удержаний.
	Refs() int64

	// Readiness проверяет готовность поколения к использованию.
	//
	// Если поколение уже завершено (удержания сняты), возвращается ошибка закрытого поколения.
	//
	// Параметры:
	//   - ctx: контекст проверки готовности.
	// Возвращаемое значение:
	//   - error: ошибка readiness callback или nil.
	Readiness(ctx context.Context) error
	// WaitForClose возвращает канал завершения поколения.
	//
	// Канал закрывается только после снятия последнего удержания.
	// Сам факт вывода поколения из активной эксплуатации не обязан немедленно закрывать канал,
	// потому что остаточные процессы могут ещё использовать поколение.
	//
	// Параметры: отсутствуют.
	// Возвращаемое значение:
	//   - <-chan struct{}: канал, закрывающийся при полном завершении поколения.
	WaitForClose() <-chan struct{}
}

// HandoverGenerationFunc начинает вывод input-поколения из активной эксплуатации
// и, при необходимости, запускает передачу ресурсов следующему поколению.
//
// Это callback уровня Generation. Он координирует lifecycle шага поколения
// и оборачивает вызов HandoverConnectionFunc, который работает уже с connection-ресурсом.
// В сигнатуре нет context.Context, потому что контекст задаётся на этапе создания поколения.
//
// Параметры:
//   - next: объект следующего поколения для передачи ресурсов; может быть nil, если передача не требуется.
//
// Возвращаемые значения:
//   - DrainingFunc: функция финального дренажа текущего поколения.
//   - error: ошибка старта передачи/закрытия.
//
// Важно: в текущей модели это одноразовый lifecycle-шаг, а не retry-механизм.
type HandoverGenerationFunc[C any] func(next *C) (rootDomain.DrainingFunc, error)

// ShutdownGenerationFunc начинает вывод output-поколения из активной эксплуатации
// и, при необходимости, запускает остановку его ресурсов.
//
// Это callback уровня Generation. Он координирует lifecycle шага поколения
// и оборачивает вызов ShutdownConnectionFunc, который выполняет остановку connection-ресурса.
// В сигнатуре нет context.Context, потому что контекст задаётся на этапе создания поколения.
//
// Возвращаемые значения:
//   - DrainingFunc: функция финального дренажа текущего поколения.
//   - error: ошибка старта остановки/закрытия.
//
// Важно: в текущей модели это одноразовый lifecycle-шаг, а не retry-механизм.
type ShutdownGenerationFunc func() (rootDomain.DrainingFunc, error)
