package domain

import (
	rootDomain "connection-keeper/domain"
	"sync"
)

// KindManager хранит и выдаёт внутренние идентификаторы типов коннекторов.
//
// Менеджер ориентирован на скорость и внутреннее использование библиотекой.
// Регистрация и создание допускают конкурентный доступ, а последовательность ID
// может содержать дырки при гонке создания — это допустимо и не считается ошибкой.
type KindManager interface {
	Kinds() *sync.Map
	Next() uint32
	GetOrCreateName(s string) (string, string, error)

	// RegisterName регистрирует отображаемое имя kind без немедленного создания объекта kind.
	// Параметры:
	//   - s: имя типа коннектора.
	// Возвращаемое значение:
	//   - error: ErrInvalidKind для пустого имени или ErrKindAlreadyRegistered при повторной регистрации.
	RegisterName(s string) error
	// GetOrCreate возвращает существующий kind по имени или создаёт новый.
	// Поиск выполняется без учёта регистра, а пробелы по краям имени отбрасываются.
	// Параметры:
	//   - s: имя типа коннектора.
	// Возвращаемые значения:
	//   - kind: найденный или созданный kind.
	//   - created: true, если kind был создан в этом вызове; false, если уже существовал.
	//   - err: ErrInvalidKind, если имя пустое после нормализации.
	GetOrCreate(s string) (kind rootDomain.Kind, created bool, err error)
	// UnsaveGetOrCreate возвращает kind по уже подготовленному ключу или создаёт его без дополнительной валидации.
	// Метод предназначен для быстрого внутреннего пути, где вызывающая сторона уже гарантирует корректность ключа.
	// Параметры:
	//   - sk: нормализованный ключ kind, обычно в нижнем регистре.
	//   - sv: отображаемое имя kind.
	// Возвращаемые значения:
	//   - kind: найденный или созданный kind.
	//   - created: true, если kind был создан в этом вызове; false, если уже существовал.
	UnsaveGetOrCreate(sk, sv string) (kind rootDomain.Kind, created bool)

	// Delete удаляет kind из менеджера. Метод предназначен ТОЛЬКО для внутреннего использования
	// в пакете connector/func.go при откате регистрации, если регистрация коннектора завершилась ошибкой.
	//
	// ВНИМАНИЕ: использование этого метода снаружи может привести к непредсказуемым ошибкам и нарушению
	// инвариантов библиотеки. Если kind уже был зарегистрирован в коннекторе, его удаление приведёт к рассинхронизации
	// состояния между КindManager, RegistryManager и ConnectorManager, что вызовет краши при работе с этим kind'ом.
	//
	// Ради скорости никаких проверок на доступность или синхронизацию с другими менеджерами не выполняется.
	//
	// Параметры:
	//   - kind: kind, который нужно удалить из менеджера.
	Delete(kind rootDomain.Kind)
}
